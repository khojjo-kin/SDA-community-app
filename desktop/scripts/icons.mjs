// Copies the iPhone app's icon set (src/components/Icon.tsx) into src/ui/icons.gen.ts.
import fs from 'node:fs';
import path from 'node:path';
const here = path.dirname(new URL(import.meta.url).pathname);
const src = fs.readFileSync(path.join(here, '../../src/components/Icon.tsx'), 'utf8');
const start = src.indexOf('const ICONS = {');
const end = src.indexOf('\n};', start);
let body = src.slice(start + 'const ICONS = '.length, end + 2);
// Icons the desktop layout needs that the iPhone app does not have.
const extra = {
  compass: '<circle cx="12" cy="12" r="8.6"/><path d="m15.6 8.4-2.1 5.1-5.1 2.1 2.1-5.1z"/>',
  newchat: '<path d="M12 4.2H7.4a3.2 3.2 0 0 0-3.2 3.2v9.2a3.2 3.2 0 0 0 3.2 3.2h9.2a3.2 3.2 0 0 0 3.2-3.2V12"/><path d="M18.3 3.3a1.9 1.9 0 0 1 2.7 2.7l-8.3 8.3-3.6 1 1-3.6z"/>',
};
body = body.replace(/\n\}$/, '\n' + Object.entries(extra).map(([k, v]) => `  ${k}: '${v}',`).join('\n') + '\n}');
fs.writeFileSync(path.join(here, '../src/ui/icons.gen.ts'), '// Generated by scripts/icons.mjs from the iPhone app. Do not edit.\nexport const ICONS = ' + body + ' as const;\nexport type IconName = keyof typeof ICONS;\n');
